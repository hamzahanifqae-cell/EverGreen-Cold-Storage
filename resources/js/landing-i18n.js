export const resolveLanguage = () => {
    try {
        const stored = localStorage.getItem(LANG_KEY);
        if (stored === 'en' || stored === 'ur') {
            return stored;
        }
    } catch {
        // Ignore storage failures.
    }

    return 'en';
};

export const applyLanguage = (lang) => {
    const safeLang = lang === 'ur' ? 'ur' : 'en';
    const dict = translations[safeLang];
    const root = document.documentElement;

    root.setAttribute('data-lang', safeLang);
    root.setAttribute('lang', safeLang === 'ur' ? 'ur' : 'en');
    root.setAttribute('dir', safeLang === 'ur' ? 'rtl' : 'ltr');

    document.querySelectorAll('[data-i18n]').forEach((node) => {
        const key = node.getAttribute('data-i18n');
        if (key && Object.prototype.hasOwnProperty.call(dict, key)) {
            node.textContent = dict[key];
        }
    });

    document.querySelectorAll('[data-i18n-aria]').forEach((node) => {
        const key = node.getAttribute('data-i18n-aria');
        if (key && Object.prototype.hasOwnProperty.call(dict, key)) {
            node.setAttribute('aria-label', dict[key]);
        }
    });

    document.querySelectorAll('[data-i18n-title]').forEach((node) => {
        const key = node.getAttribute('data-i18n-title');
        if (key && Object.prototype.hasOwnProperty.call(dict, key)) {
            node.setAttribute('title', dict[key]);
        }
    });

    const page = document.body?.dataset?.landingPage;
    const titleKey = page === 'guide' ? 'meta.title.guide' : 'meta.title.landing';
    if (Object.prototype.hasOwnProperty.call(dict, titleKey)) {
        document.title = dict[titleKey];
    }

    const langToggle = document.querySelector('[data-lang-toggle]');
    if (langToggle) {
        const nextLabel = safeLang === 'ur' ? dict['lang.toEn'] : dict['lang.toUr'];
        langToggle.setAttribute('aria-label', nextLabel);
        langToggle.setAttribute('title', nextLabel);
        langToggle.setAttribute('aria-pressed', safeLang === 'ur' ? 'true' : 'false');
    }

    const themeToggle = document.querySelector('[data-theme-toggle]');
    if (themeToggle) {
        const theme = root.getAttribute('data-theme') === 'dark' ? 'dark' : 'light';
        const themeKey = theme === 'dark' ? 'theme.toLight' : 'theme.toDark';
        themeToggle.setAttribute('aria-label', dict[themeKey]);
        themeToggle.setAttribute('title', dict[themeKey]);
    }
};

export const setLanguage = (lang) => {
    applyLanguage(lang);

    try {
        localStorage.setItem(LANG_KEY, lang === 'ur' ? 'ur' : 'en');
    } catch {
        // Ignore storage failures.
    }
};
